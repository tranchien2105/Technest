import assert from "node:assert/strict";
import { writeFile, mkdir } from "node:fs/promises";
import { openBrowser, pause } from "./browser-cdp.mjs";
const base = "http://127.0.0.1:4175";
const fixture = await (await fetch(`${base}/__e2e/fixture`)).json();
assert.ok(fixture.adminCredentials, "Transactional admin fixture required");
const browser = await openBrowser({ port: 19224 });
const results = [];
const waitForList = () => browser.wait("!!document.querySelector('.admin-products-table tbody tr') && !document.querySelector('.admin-loading-line')", "admin product list settled");
try {
  await browser.viewport(1440);
  await browser.navigate(`${base}/admin/products`);
  await browser.wait("!!document.querySelector('.admin-login-card input[name=email]')");
  await browser.fill('.admin-login-card input[name="email"]', fixture.adminCredentials.email);
  await browser.fill('.admin-login-card input[name="password"]', fixture.adminCredentials.password);
  await browser.click('.admin-login-card button[type="submit"]');
  await waitForList();
  assert.equal(browser.responses.filter((response) => response.url.includes("products/references")).length, 0, "No reference preload");
  await browser.evaluate("(() => { const original=window.fetch; window.__adminCalls=[]; window.fetch=(input,options)=>{window.__adminCalls.push({url:String(input),method:options?.method||'GET'});return original(input,options);}; })()");
  results.push({ check: "Real admin login; initial catalog has no brand/category reference preload", result: "PASS" });
  for (const text of ["L", "Lo", "Log", "Logitech"]) { await browser.fill('input[aria-label="Tìm sản phẩm"]', text); await pause(50); }
  await pause(500); await waitForList();
  const searchCalls = await browser.evaluate("window.__adminCalls.filter(call=>/\\/admin\\/products\\?/.test(call.url))");
  assert.equal(searchCalls.length, 1, JSON.stringify(searchCalls));
  assert.equal(new URL(searchCalls[0].url, base).searchParams.get("q"), "Logitech");
  results.push({ check: "Four rapid search changes generate one settled listing request", requests: searchCalls, result: "PASS" });
  const pageOne = await browser.evaluate("[...document.querySelectorAll('.admin-products-table tbody tr')].map(row=>row.querySelector('.admin-product-info small').textContent)");
  await browser.click('button[aria-label="Trang sau"]');
  await browser.wait("document.querySelector('.admin-page-navigation strong')?.textContent==='2'");
  await waitForList();
  const pageTwo = await browser.evaluate("[...document.querySelectorAll('.admin-products-table tbody tr')].map(row=>row.querySelector('.admin-product-info small').textContent)");
  assert.ok(pageTwo.every((id) => !pageOne.includes(id)), "Pagination has no duplicate products");
  await browser.click('.admin-sidebar a[href="/admin/brands"]');
  await browser.wait("location.pathname==='/admin/brands' && !!document.querySelector('.admin-brands-table tbody tr')");
  await browser.evaluate("history.back()");
  await browser.wait("location.pathname==='/admin/products' && document.querySelector('input[aria-label=\"Tìm sản phẩm\"]')?.value==='Logitech' && document.querySelector('.admin-page-navigation strong')?.textContent==='2'");
  await waitForList();
  results.push({ check: "Distinct pagination and browser Back preserve search/page", firstPageCount: pageOne.length, secondPageCount: pageTwo.length, result: "PASS" });
  await browser.evaluate("(() => { const input=document.querySelector('input[role=combobox][aria-label=\"Thương hiệu\"]'); input.focus(); input.click(); })()");
  await browser.wait("document.querySelectorAll('.admin-reference-popover [role=option]').length>0");
  const initialOptions = await browser.evaluate("document.querySelectorAll('.admin-reference-popover [role=option]').length");
  assert.ok(initialOptions <= 30);
  await browser.fill('input[role="combobox"][aria-label="Thương hiệu"]', "Logitech");
  await pause(400);
  await browser.wait("[...document.querySelectorAll('.admin-reference-popover [role=option]')].some(option=>option.textContent.toLowerCase()==='logitech')");
  await browser.evaluate("[...document.querySelectorAll('.admin-reference-popover [role=option]')].find(option=>option.textContent.toLowerCase()==='logitech').click()");
  await waitForList();
  const filteredCall = await browser.evaluate("window.__adminCalls.filter(call=>/\\/admin\\/products\\?/.test(call.url)).at(-1)");
  assert.ok(new URL(filteredCall.url, base).searchParams.get("brandId"));
  assert.equal(new URL(filteredCall.url, base).searchParams.get("page"), "1");
  results.push({ check: "Bounded searchable brand picker; selection filters server-side and resets page", initialOptions, result: "PASS" });
  await mkdir(new URL('../docs/screenshots/', import.meta.url), { recursive: true });
  await browser.screenshot(new URL('../docs/screenshots/admin-catalog-desktop.png', import.meta.url).pathname);
  await browser.click('.admin-products-table tbody tr button[aria-label^="Sửa "]');
  await browser.wait("!!document.querySelector('form[role=dialog] .admin-editor-fields input')");
  const originalName = await browser.evaluate("document.querySelector('form[role=dialog] .admin-editor-fields input').value");
  await browser.fill('form[role="dialog"] .admin-editor-fields input', `${originalName} draft`);
  await browser.evaluate("window.__discardPrompt='';window.confirm=(message)=>{window.__discardPrompt=message;return false;};document.querySelector('form[role=dialog] header button[aria-label=\"Đóng\"]').click()");
  assert.ok(await browser.evaluate("!!document.querySelector('form[role=dialog]') && window.__discardPrompt.includes('chưa lưu')"));
  await browser.screenshot(new URL('../docs/screenshots/admin-catalog-editor.png', import.meta.url).pathname);
  await browser.evaluate("window.confirm=()=>true;document.querySelector('form[role=dialog] header button[aria-label=\"Đóng\"]').click()");
  await browser.wait("!document.querySelector('form[role=dialog]')");
  const mutations = await browser.evaluate("window.__adminCalls.filter(call=>!['GET','HEAD'].includes(call.method))");
  assert.equal(mutations.length, 0, "No catalog writes during browser audit");
  results.push({ check: "Editor warns before discarding draft and preserves it when canceling; audit makes no catalog mutations", result: "PASS" });
  await browser.viewport(390);
  await pause(300);
  const dimensions = await browser.evaluate("({width:innerWidth,scrollWidth:document.documentElement.scrollWidth})");
  assert.ok(dimensions.scrollWidth <= dimensions.width + 1, JSON.stringify(dimensions));
  await browser.screenshot(new URL('../docs/screenshots/admin-catalog-mobile.png', import.meta.url).pathname);
  assert.deepEqual(browser.errors, []);
  results.push({ check: "390px admin catalog has no document overflow or JavaScript exceptions", ...dimensions, result: "PASS" });
  await writeFile(new URL('../docs/technest-admin-browser-results.json', import.meta.url), `${JSON.stringify({ checkedAt: new Date().toISOString(), base, fixturePolicy: "Admin registered inside a PostgreSQL transaction owned by browser-e2e-server; no real credentials or catalog writes", results, exceptions: browser.errors }, null, 2)}\n`);
  console.log(JSON.stringify({ result: "PASS", checks: results.length }));
} catch (error) {
  console.error(JSON.stringify({ phase: results.at(-1)?.check || "initial admin login", error: error.message, body: await browser.evaluate("document.body.innerText.slice(0, 2200)"), exceptions: browser.errors, httpErrors: browser.responses.filter((response) => response.status >= 400) }));
  await browser.screenshot('/tmp/technest-admin-browser-failure.png');
  throw error;
} finally { await browser.close(); }
