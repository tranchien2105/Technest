import assert from "node:assert/strict";
import { mkdir, writeFile } from "node:fs/promises";
import process from "node:process";
import console from "node:console";
import { openBrowser, pause } from "./browser-cdp.mjs";

const base = process.env.E2E_BASE || "http://127.0.0.1:4175";
const fixture = await (await fetch(`${base}/__e2e/fixture`)).json();
const artifacts = "/tmp/technest-purchase-browser";
await mkdir(artifacts, { recursive: true });
const browser = await openBrowser();
const cases = [];
const checkedAt = new Date().toISOString();
const passed = (name, evidence) => { cases.push({ name, result: "PASS", evidence }); console.log("PASS", name); };
const state = async () => (await fetch(`${base}/__e2e/state`)).json();
try {
  await browser.viewport(390);
  await browser.navigate(`${base}/login`);
  await browser.wait("!!document.querySelector('.auth-form input[name=email]')");
  await browser.fill(".auth-form input[name=email]", fixture.credentials.email);
  await browser.fill(".auth-form input[name=password]", fixture.credentials.password);
  await browser.click(".auth-form button[type=submit]");
  await browser.wait("location.pathname==='/account' && document.body.innerText.includes('Browser E2E Customer')", "Real PostgreSQL auth login");
  passed("Login through rendered form and PostgreSQL auth", { path: await browser.evaluate("location.pathname"), fixtureAccount: true });

  await browser.navigate(`${base}/`);
  await browser.wait("!!document.querySelector('header input[aria-autocomplete=list]')");
  await browser.fill("header input[aria-autocomplete=list]", "Technest Browser Keyboard");
  await browser.wait("!!document.querySelector('.search-suggestion-item[role=option]')", "Autocomplete options loaded");
  await browser.evaluate("document.querySelector('header input[aria-autocomplete=list]').focus()");
  await browser.send("Input.dispatchKeyEvent", { type: "keyDown", key: "ArrowDown", code: "ArrowDown", windowsVirtualKeyCode: 40 });
  await browser.send("Input.dispatchKeyEvent", { type: "keyUp", key: "ArrowDown", code: "ArrowDown", windowsVirtualKeyCode: 40 });
  await browser.wait("document.querySelector('input[role=combobox]')?.getAttribute('aria-activedescendant')===document.querySelector('.search-suggestion-item[aria-selected=true]')?.id");
  await browser.send("Input.dispatchKeyEvent", { type: "keyDown", key: "Enter", code: "Enter", windowsVirtualKeyCode: 13 });
  await browser.send("Input.dispatchKeyEvent", { type: "keyUp", key: "Enter", code: "Enter", windowsVirtualKeyCode: 13 });
  await browser.wait(`location.pathname==='/products/${fixture.slug}' && !!document.querySelector('.detail-variant-select select')`);
  passed("Autocomplete ArrowDown + Enter selects product with valid ARIA", { path: await browser.evaluate("location.pathname") });
  await browser.navigate(`${base}/`);
  await browser.wait("!!document.querySelector('header input[aria-autocomplete=list]')");
  await browser.fill("header input[aria-autocomplete=list]", "Technest Browser Keyboard");
  await browser.evaluate("document.querySelector('header form[role=search]').requestSubmit()");
  await browser.wait(`location.pathname==='/search' && !!document.querySelector('a[href="/products/${fixture.slug}"]')`, "Search returns transaction fixture");
  passed("Header search → Product Listing", { query: await browser.evaluate("location.search") });
  await browser.click(`a[href="/products/${fixture.slug}"]`);
  await browser.wait("!!document.querySelector('.detail-variant-select select')");
  await browser.fill(".detail-variant-select select", fixture.variants[2].id);
  await browser.wait("document.querySelector('.detail-purchase-cart')?.disabled===true", "Sold-out variant blocks purchase");
  passed("Sold-out variant disables Add to Cart and Buy Now", await browser.evaluate("({cartDisabled:document.querySelector('.detail-purchase-cart').disabled,buyDisabled:document.querySelector('.detail-purchase-buy').disabled})"));
  await browser.fill(".detail-variant-select select", fixture.variants[1].id);
  await browser.wait("document.querySelector('.detail-purchase-cart')?.disabled===false && document.querySelector('.detail-purchase-total').innerText.includes('150.000')");
  await browser.click(".detail-buy-row button[aria-label='Tăng số lượng']");
  await browser.wait("document.querySelector('.detail-purchase-total').innerText.includes('300.000')");
  await browser.click(".detail-purchase-cart");
  await browser.wait("JSON.parse(localStorage.getItem('technest-cart')||'[]').some(x=>x.quantity===2)");
  passed("Variant price, quantity and Add to Cart", await browser.evaluate("JSON.parse(localStorage.getItem('technest-cart')).map(x=>({variantId:x.variantId,quantity:x.quantity,price:x.price}))"));

  await browser.navigate(`${base}/cart`);
  await browser.wait("!!document.querySelector('.cart-page-item') && !document.querySelector('.order-summary button.primary-button').disabled");
  assert.equal(await browser.evaluate("document.querySelector('.cart-page-info .quantity-control span').textContent"), "2");
  passed("Cart persists through full reload with current stock", { quantity: 2 });
  await browser.click(".order-summary button.primary-button");
  await browser.wait("!!document.querySelector('form.checkout-layout')");
  await browser.click(".checkout-submit");
  assert.equal((await state()).orders.length, 0);
  assert.equal(await browser.evaluate("document.querySelector('form.checkout-layout').checkValidity()"), false);
  passed("Required form fields prevent empty checkout submission", { actualOrders: 0 });

  await browser.fill("input[name=name]", "Browser E2E Customer");
  await browser.fill("input[name=email]", fixture.credentials.email);
  await browser.fill("input[name=phone]", "0901234567");
  await browser.fill("input[name=address]", "1 Transaction Fixture Street");
  await browser.fill("select[name=city]", "Hồ Chí Minh");
  await browser.wait("document.querySelector('select[name=district]').options.length>1");
  const district = await browser.evaluate("document.querySelector('select[name=district]').options[1].value");
  await browser.fill("select[name=district]", district);
  await browser.wait("document.querySelector('select[name=ward]').options.length>1");
  const ward = await browser.evaluate("document.querySelector('select[name=ward]').options[1].value");
  await browser.fill("select[name=ward]", ward);
  await browser.click("input[name=saveAddress]");
  await fetch(`${base}/__e2e/price`, { method: "POST", headers: { "Content-Type": "application/json" }, body: JSON.stringify({ variantId: fixture.variants[1].id, price: 160000 }) });
  await browser.click(".checkout-voucher button");
  await browser.wait("document.querySelector('.checkout-summary-item').innerText.includes('160.000') && document.querySelector('.checkout-grand-total').innerText.includes('350.000')", "Quote uses actual new variant price for rows and totals");
  passed("Server repricing updates checkout line and total together", { unitPrice: 160000, total: 350000 });
  await browser.fill("#checkout-voucher", "CHANGED");
  await browser.wait("document.querySelector('.checkout-summary-item').innerText.includes('150.000') && document.querySelector('.checkout-grand-total').innerText.includes('330.000')", "Voucher edit invalidates prior quote");
  await browser.fill("#checkout-voucher", "");
  await fetch(`${base}/__e2e/price`, { method: "POST", headers: { "Content-Type": "application/json" }, body: JSON.stringify({ variantId: fixture.variants[1].id, price: 150000 }) });
  passed("Voucher edit invalidates stale quote rows and totals", { restoredFixturePrice: 150000 });
  await browser.screenshot(`${artifacts}/checkout-mobile.png`);
  assert.equal(await browser.evaluate("document.querySelector('form.checkout-layout').checkValidity()"), true);
  await browser.evaluate("document.querySelector('form.checkout-layout').requestSubmit();document.querySelector('form.checkout-layout').requestSubmit()");
  await browser.wait("!!document.querySelector('.checkout-form-layout [role=alert]')", "Lost order acknowledgement shows recoverable error");
  const lost = await state();
  assert.equal(lost.orders.length, 1);
  assert.equal(lost.requests.length, 1);
  assert.equal(lost.droppedResponses, 1);
  assert.equal(lost.addresses, 1, "Double submit creates just one saved address");
  assert.equal(await browser.evaluate("document.querySelector('input[name=address]').value"), "1 Transaction Fixture Street");
  assert.ok(await browser.evaluate("!!sessionStorage.getItem('technest-checkout-retry')"));
  passed("Lost acknowledgement: form retained and double-submit blocked", { actualOrders: lost.orders.length, createRequests: lost.requests.length, injectedFault: "Gateway 503 substituted after real PostgreSQL order creation" });

  await browser.evaluate("document.querySelector('form.checkout-layout').requestSubmit();document.querySelector('form.checkout-layout').requestSubmit()");
  await browser.wait("location.pathname.startsWith('/order-success/') && !!document.querySelector('.success-page')", "Retry reuses order and shows server-confirmed success");
  const complete = await state();
  assert.equal(complete.orders.length, 1);
  assert.equal(complete.addresses, 1, "Retry reuses the saved address");
  assert.equal(complete.requests.length, 2);
  assert.equal(complete.requests[0].key, complete.requests[1].key);
  assert.equal(complete.orders[0].paymentMethod, "COD");
  assert.equal(complete.orders[0].total, "330000");
  assert.equal(await browser.evaluate("JSON.parse(localStorage.getItem('technest-cart')).length"), 0);
  passed("Retry uses same idempotency key; exactly one COD order", complete);
  await browser.screenshot(`${artifacts}/order-success-mobile.png`);

  await browser.navigate(`${base}/account/orders`);
  await browser.wait("!!document.querySelector('.account-order-card') || document.body.innerText.includes('330.000')", "Order history contains PostgreSQL order");
  assert.ok(await browser.evaluate("document.body.innerText.includes('330.000')"));
  passed("Order History displays actual COD order", { orderId: complete.orders[0].id, total: "330000" });

  await browser.navigate(`${base}/products/${fixture.slug}?variant=${fixture.variants[0].id}`);
  await browser.wait("!!document.querySelector('.detail-purchase-cart') && !document.querySelector('.detail-purchase-cart').disabled");
  await browser.click(".detail-purchase-cart");
  await browser.navigate(`${base}/cart`);
  await browser.wait("!!document.querySelector('.cart-page-item') && !document.querySelector('.order-summary button.primary-button').disabled");
  await browser.screenshot(`${artifacts}/cart-mobile.png`);
  await browser.click(".order-summary button.primary-button");
  await browser.wait("!!document.querySelector('form.checkout-layout')");
  // Only this fixture's stock changes. A competitor consuming the last unit is
  // represented by setting stock to zero between UI load and server preview.
  const stockResponse = await fetch(`${base}/__e2e/stock`, { method: "POST", headers: { "Content-Type": "application/json" }, body: JSON.stringify({ variantId: fixture.variants[0].id, onHand: 0 }) });
  assert.equal(stockResponse.ok, true, "Stock fault must be successfully injected before testing checkout");
  assert.equal((await state()).stock.find((item) => item.id === fixture.variants[0].id).onHand, 0);
  for (const [selector, value] of [["input[name=name]", "Browser E2E Customer"], ["input[name=email]", fixture.credentials.email], ["input[name=phone]", "0901234567"], ["input[name=address]", "1 Transaction Fixture Street"], ["select[name=city]", "Hồ Chí Minh"]]) await browser.fill(selector, value);
  await browser.fill("select[name=district]", district); await browser.fill("select[name=ward]", ward);
  await browser.click(".checkout-submit");
  await browser.wait("!!document.querySelector('.checkout-form-layout [role=alert]')", "Stock changed: checkout shows error");
  assert.equal((await state()).orders.length, 1);
  passed("Stock change before checkout prevents second order", { actualOrders: 1, message: await browser.evaluate("document.querySelector('.checkout-form-layout [role=alert]').textContent") });
  assert.equal(browser.errors.length, 0, "No unhandled JavaScript exceptions");
  await writeFile(new URL("../docs/technest-purchase-browser-results.json", import.meta.url), JSON.stringify({ checkedAt, browser: "Chromium headless via CDP", base, database: "technest_dev; one outer transaction; fixtures rollback", scaffolding: ["same-origin production frontend build", "isolated in-memory auth rate limiter", "noindex metadata test endpoint", "one dropped HTTP success acknowledgement"], cases, exceptions: browser.errors, artifacts }, null, 2));
  console.log("BROWSER_PURCHASE_COMPLETE", cases.length);
} catch (error) {
  await browser.screenshot(`${artifacts}/failure.png`).catch(() => {});
  const debug = await browser.evaluate("({url:location.href,text:document.body.innerText.slice(-9000),html:document.querySelector('main')?.outerHTML.slice(0,3000)})").catch(() => null);
  await writeFile(`${artifacts}/failure.json`, JSON.stringify({ cases, message: error.message, debug, exceptions: browser.errors, responses: browser.responses.filter((response) => response.status >= 400), networkFailures: browser.networkFailures }, null, 2));
  throw error;
} finally { await browser.close(); await pause(100); }
